-- 021: 服務條款補充存書／取書期限、撥款時間、存書後不得自行取消與預約保留規則
--   mysql -u <帳號> -p <資料庫名稱> < migrations/021_terms_payout.sql
-- 可重複執行；內容已更新過就不會再改版。更新後版本號加一，使用者下次開啟 App 須重新同意。
-- 以原句替換：若條款曾在後台修改過而找不到原句，該句不會變更，請看最後的查詢結果並至後台手動補上。

UPDATE legal_documents
SET content = REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(content,
      '並於訂單成立後，依約定期限將書籍放入指定之智慧書櫃。',
      '並於訂單成立後 7 日內將書籍放入指定之智慧書櫃。'),
      '於規定期限內前往指定智慧書櫃',
      '於書籍放入後 7 日內前往指定智慧書櫃'),
      '(3) 若買賣任一方未於期限內完成放書或取書，系統將自動取消訂單，並可能影響未履行義務方之會員信用評分。',
      '(3) 若賣家未於期限內放書，或買家未於期限內取書，系統將自動取消訂單並將款項全額退回買家，並可能影響未履行義務方之會員信用評分。賣家放書後，買賣雙方均不得自行取消訂單，如有問題應依第 7 條提出交易申訴。'),
      '(4) 書籍預約僅為保留意願之表示，賣家得於期限內接受或婉拒。',
      '(4) 書籍預約僅為保留意願之表示，賣家得於期限內接受或婉拒。賣家接受後，於保留期間內其他買家無法購買該書籍，賣家亦不得編輯或下架。\n(5) 買家付款後，款項由本平台代為保管；買家取書後點選「完成訂單」，或取書滿 24 小時未提出交易申訴者，訂單即自動完成，款項撥入賣家之電子錢包。'),
      '可於取件後 24 小時內透過系統發起「交易申訴」。',
      '可於取件後 24 小時內、訂單完成前透過系統發起「交易申訴」；訂單完成後不再受理申訴。'),
    version = version + 1,
    requires_consent = 1,
    updated_at = NOW()
WHERE doc_key = 'terms' AND content NOT LIKE '%代為保管%';

SELECT
  version AS '服務條款版本',
  IF(content LIKE '%代為保管%', '已包含撥款規則', '未更新，請至後台手動補上') AS '撥款規則',
  IF(content LIKE '%7 日內將書籍放入%', '已更新', '未找到原句') AS '存書期限',
  IF(content LIKE '%訂單完成後不再受理申訴%', '已更新', '未找到原句') AS '申訴期限'
FROM legal_documents WHERE doc_key = 'terms';
