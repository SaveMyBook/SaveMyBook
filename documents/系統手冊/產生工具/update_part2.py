def uc_set(tbl, key, lines):
    set_cell(tcs(row_by_key(tbl, key))[1], lines)

def uc_append(tbl, key, lines):
    tc = tcs(row_by_key(tbl, key))[1]
    current = [text_of(p) for p in tc.findall(W('p'))]
    set_cell(tc, current + lines)

def uc_replace(tbl, key, old, new):
    tc = tcs(row_by_key(tbl, key))[1]
    lines = [text_of(p) for p in tc.findall(W('p'))]
    joined = '\n'.join(lines)
    assert old in joined, (key, old)
    set_cell(tc, joined.replace(old, new).split('\n'))

def req_set(tbl, key, text):
    set_cell(tcs(row_by_key(tbl, key))[1], text)

def req_add(tbl, key, text):
    rows = tbl.findall(W('tr'))
    new = clone_row_after(rows[-1])
    set_cell(tcs(new)[0], key); set_cell(tcs(new)[1], text)

def req_rename(tbl, key, new_key, text):
    tr = row_by_key(tbl, key)
    set_cell(tcs(tr)[0], new_key); set_cell(tcs(tr)[1], text)

def req_insert_after(tbl, key, new_key, text):
    new = clone_row_after(row_by_key(tbl, key))
    set_cell(tcs(new)[0], new_key); set_cell(tcs(new)[1], text)

def req_append(tbl, key, text):
    tc = tcs(row_by_key(tbl, key))[1]
    set_cell(tc, text_of(tc) + text)

def para_starting(doc, prefix):
    for p in doc.paragraphs:
        if p.style.name != 'table of figures' and p.text.strip().startswith(prefix): return p
    raise KeyError(prefix)

